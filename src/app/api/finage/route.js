import { NextResponse } from 'next/server';
import { executeFinagePipeline } from '@/lib/finage';
import { generateSimulatedCandles } from '@/lib/simulatedMarket';

const CACHE_TTL_MS = 60_000;
const MAX_CACHE_ENTRIES = 50;
const responseCache = new Map();
const pendingRequests = new Map();

function getCachedResponse(cacheKey) {
  const cached = responseCache.get(cacheKey);
  if (!cached || Date.now() - cached.createdAt > CACHE_TTL_MS) {
    responseCache.delete(cacheKey);
    return null;
  }

  responseCache.delete(cacheKey);
  responseCache.set(cacheKey, cached);
  return cached.data;
}

function setCachedResponse(cacheKey, data) {
  if (responseCache.size >= MAX_CACHE_ENTRIES) {
    const oldestKey = responseCache.keys().next().value;
    responseCache.delete(oldestKey);
  }

  responseCache.set(cacheKey, { data, createdAt: Date.now() });
}

export async function GET(request) {
  const { searchParams } = new URL(request.url);
  const symbol = searchParams.get('symbol');
  const timeframe = searchParams.get('timeframe') || '15m';
  const start = searchParams.get('start');
  const end = searchParams.get('end');
  const inclusive = searchParams.get('inclusive') === 'true';

  if (!symbol || !start || !end) {
    return NextResponse.json({ error: 'Missing required query parameters' }, { status: 400 });
  }

  const apiKey = process.env.FINAGE_API_KEY || 'API_KEY95YTO81R66DCOZUANVVX135GBVHXQ5CK';
  const formattedSymbol = symbol.replace(/\//g, '').toLowerCase();
  const cacheKey = `${formattedSymbol}|${timeframe}|${start}|${end}|${inclusive}`;

  const cachedResponse = getCachedResponse(cacheKey);
  if (cachedResponse) {
    return NextResponse.json(cachedResponse, {
      headers: { 'Cache-Control': 'private, max-age=60' },
    });
  }

  if (pendingRequests.has(cacheKey)) {
    const pendingResponse = await pendingRequests.get(cacheKey);
    return NextResponse.json(pendingResponse, {
      headers: { 'Cache-Control': 'private, max-age=60' },
    });
  }

  try {
    const pendingRequest = (async () => {
      const result = await executeFinagePipeline({
        symbol,
        startDate: start,
        endDate: end,
        timeframe,
        apiKey,
        chunkHours: 48,
        concurrency: 3,
        inclusiveEnd: inclusive,
        allowSimulationFallback: true,
      });

      const responsePayload = {
        candles: result.candles,
        telemetry: result.telemetry,
        chunks: result.chunks,
        isSimulated: result.isSimulated || false,
        notice: result.notice,
      };

      setCachedResponse(cacheKey, responsePayload);
      return responsePayload;
    })().finally(() => {
      pendingRequests.delete(cacheKey);
    });

    pendingRequests.set(cacheKey, pendingRequest);
    const responseData = await pendingRequest;

    return NextResponse.json(responseData, {
      headers: { 'Cache-Control': 'private, max-age=60' },
    });
  } catch (error) {
    console.error('Pipeline Execution Error, serving simulated fallback:', error);
    const simulatedCandles = generateSimulatedCandles(symbol, timeframe, start, end);
    const normalized = simulatedCandles.map(c => ({
      timestamp: c.time,
      time: c.time,
      open: c.open,
      high: c.high,
      low: c.low,
      close: c.close,
      volume: c.volume || 100,
    }));

    const fallback = {
      candles: normalized,
      isSimulated: true,
      notice: 'Demo Mode: Finage API offline. Market data is generated by the local simulator.',
      telemetry: {
        totalChunks: 1,
        completedChunks: 1,
        rawRowsReceived: normalized.length,
        validCandles: normalized.length,
        duplicatesRemoved: 0,
        conflictsResolved: 0,
        intradayMissingMinutes: 0,
        weekendClosureMinutes: 0,
        firstTimestamp: normalized[0]?.timestamp || 0,
        lastTimestamp: normalized[normalized.length - 1]?.timestamp || 0,
      },
    };

    return NextResponse.json(fallback, {
      headers: { 'Cache-Control': 'private, max-age=60' },
    });
  }
}
